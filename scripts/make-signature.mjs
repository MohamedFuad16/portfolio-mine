// Turns "Mohamed Fuad" into per-glyph outline paths from La Storia Bold, the
// font behind Spell UI's <Signature>. Run once; the output is committed so the
// page ships no font file and no opentype.js.
//
//   node scripts/make-signature.mjs
//
// Layout mirrors the Spell component: 100-unit tall box, glyphs placed on one
// baseline by advance width (plus kerning), padding of 10% of the font size.
// Path data is serialized by hand because toPathData() can fuse numbers
// ("152.20Q"), which makes browsers drop the rest of the path (ADR in
// agent/decisions.md on the Great Vibes signature).
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const TEXT = 'Mohamed Fuad';
const FONT_SIZE = 64;
const SVG_HEIGHT = 100;
const FONT = new URL('./fonts/LastoriaBoldRegular.otf', import.meta.url);
const OUT = new URL('../src/data/signature-path.js', import.meta.url);

const buffer = readFileSync(FONT);
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const scale = FONT_SIZE / font.unitsPerEm;
const padding = FONT_SIZE * 0.1;
const topMargin = Math.max(5, (SVG_HEIGHT - FONT_SIZE) / 2);
const baseline = Math.min(SVG_HEIGHT - 5, topMargin + FONT_SIZE);

const n = (value) => String(Math.round(value * 100) / 100);
const serialize = (commands) => commands.map((c) => {
  switch (c.type) {
    case 'M': case 'L': return `${c.type}${n(c.x)} ${n(c.y)}`;
    case 'Q': return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
    case 'C': return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
    case 'Z': return 'Z';
    default: throw new Error(`unknown command ${c.type}`);
  }
}).join(' ');

// Points on the drawn curves. opentype's getBoundingBox() counts control
// points, which sit far outside this font's swashes and left a blank band
// under the name.
function* inkPoints(commands) {
  let cx = 0;
  let cy = 0;
  for (const c of commands) {
    if (c.type === 'Q' || c.type === 'C') {
      for (let t = 0; t <= 1; t += 1 / 24) {
        const u = 1 - t;
        yield c.type === 'Q'
          ? [u * u * cx + 2 * u * t * c.x1 + t * t * c.x, u * u * cy + 2 * u * t * c.y1 + t * t * c.y]
          : [u ** 3 * cx + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t ** 3 * c.x,
             u ** 3 * cy + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t ** 3 * c.y];
      }
    }
    if (c.type !== 'Z') {
      cx = c.x;
      cy = c.y;
      yield [cx, cy];
    }
  }
}

let x = padding;
let previous = null;
const glyphs = [];
const box = { x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity };
for (const char of TEXT) {
  const glyph = font.charToGlyph(char);
  if (previous) x += font.getKerningValue(previous, glyph) * scale;
  const path = glyph.getPath(x, baseline, FONT_SIZE);
  const d = serialize(path.commands);
  if (d) {
    glyphs.push(d);
    for (const [px, py] of inkPoints(path.commands)) {
      box.x1 = Math.min(box.x1, px); box.y1 = Math.min(box.y1, py);
      box.x2 = Math.max(box.x2, px); box.y2 = Math.max(box.y2, py);
    }
  }
  x += (glyph.advanceWidth ?? font.unitsPerEm) * scale;
  previous = glyph;
}
// Script fonts swing well outside the advance box, so the viewBox is the
// real ink bounds plus the component's padding, not the 100-unit layout box.
const viewBox = [box.x1 - padding, box.y1 - padding, box.x2 - box.x1 + padding * 2, box.y2 - box.y1 + padding * 2]
  .map((value) => Math.round(value * 10) / 10)
  .join(' ');

writeFileSync(OUT, `// Generated by scripts/make-signature.mjs from La Storia Bold (Spell UI's
// Signature font). One outline path per glyph, in writing order. Do not edit.
export const signatureViewBox = '${viewBox}';
export const signatureFontSize = ${FONT_SIZE};
export const signatureGlyphs = ${JSON.stringify(glyphs, null, 2)};
`);
console.log(`${glyphs.length} glyphs, viewBox ${viewBox}`);
